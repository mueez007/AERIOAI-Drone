import os
from datetime import datetime
from typing import Optional

from config import settings
from core.database import SessionLocal
from core.models import Mission, Media, Detection


def generate_mission_pdf(mission_id: str) -> Optional[str]:
    """Generate a PDF report for a completed mission."""
    db = SessionLocal()
    try:
        mission = db.query(Mission).filter(Mission.id == mission_id).first()
        if not mission:
            return None

        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib.colors import HexColor, black, white
        from reportlab.platypus import (
            SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
        )
        from reportlab.lib.units import inch

        filename = f"report_{mission.id}_{datetime.now().strftime('%Y%m%d_%H%M%S')}.pdf"
        filepath = os.path.join(settings.MEDIA_PATH, "reports", filename)
        os.makedirs(os.path.dirname(filepath), exist_ok=True)

        doc = SimpleDocTemplate(filepath, pagesize=A4)
        styles = getSampleStyleSheet()
        story = []

        # Title
        title_style = ParagraphStyle(
            "Title", fontSize=24, textColor=HexColor("#00FFFF"), spaceAfter=10
        )
        story.append(Paragraph("AERIOAI Mission Report", title_style))
        story.append(Spacer(1, 0.2 * inch))

        # Mission Info
        info_style = ParagraphStyle("Info", fontSize=12, textColor=black, spaceAfter=5)
        story.append(Paragraph(f"<b>Mission:</b> {mission.name}", info_style))
        story.append(Paragraph(f"<b>Mission ID:</b> {mission.id}", info_style))
        story.append(Paragraph(f"<b>Pilot ID:</b> {mission.pilot_id}", info_style))
        story.append(Paragraph(f"<b>Status:</b> {mission.status}", info_style))
        story.append(Paragraph(f"<b>Started:</b> {mission.started_at}", info_style))
        story.append(Paragraph(f"<b>Ended:</b> {mission.ended_at}", info_style))
        story.append(Spacer(1, 0.2 * inch))

        # Flight Statistics
        story.append(Paragraph("<b>Flight Statistics</b>", info_style))
        stats_data = [
            ["Metric", "Value"],
            ["Duration", f"{mission.duration_seconds}s" if mission.duration_seconds else "N/A"],
            ["Distance", f"{mission.distance_meters}m" if mission.distance_meters else "N/A"],
            ["Avg Speed", f"{mission.avg_speed} km/h" if mission.avg_speed else "N/A"],
            ["Max Altitude", f"{mission.max_altitude}m" if mission.max_altitude else "N/A"],
        ]
        stats_table = Table(stats_data, colWidths=[200, 200])
        stats_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), HexColor("#101827")),
            ("TEXTCOLOR", (0, 0), (-1, 0), HexColor("#00FFFF")),
            ("GRID", (0, 0), (-1, -1), 1, HexColor("#1a3a4a")),
            ("BACKGROUND", (0, 1), (-1, -1), white),
        ]))
        story.append(stats_table)
        story.append(Spacer(1, 0.2 * inch))

        # AI Analysis
        story.append(Paragraph("<b>AI Analysis</b>", info_style))
        analysis_data = [
            ["Metric", "Value"],
            ["Objects Detected", str(mission.total_objects_detected)],
            ["Threats Found", str(mission.total_threats)],
            ["Threat Score", f"{mission.threat_score}%"],
            ["Coverage Score", f"{mission.coverage_score}%"],
            ["Mission Success", f"{mission.mission_success}%"],
        ]
        analysis_table = Table(analysis_data, colWidths=[200, 200])
        analysis_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), HexColor("#101827")),
            ("TEXTCOLOR", (0, 0), (-1, 0), HexColor("#00FFFF")),
            ("GRID", (0, 0), (-1, -1), 1, HexColor("#1a3a4a")),
            ("BACKGROUND", (0, 1), (-1, -1), white),
        ]))
        story.append(analysis_table)
        story.append(Spacer(1, 0.3 * inch))

        # Summary
        if mission.summary:
            story.append(Paragraph("<b>Mission Summary</b>", info_style))
            story.append(Paragraph(mission.summary, info_style))

        # Footer
        story.append(Spacer(1, 0.5 * inch))
        footer_style = ParagraphStyle("Footer", fontSize=8, textColor=HexColor("#666666"))
        story.append(Paragraph(f"Generated by AERIOAI Mission Intelligence Platform | {datetime.now()}", footer_style))

        doc.build(story)
        return filepath

    except Exception as e:
        print(f"PDF generation error: {e}")
        return None
    finally:
        db.close()


def generate_mission_csv(mission_id: str) -> Optional[str]:
    """Export mission detections as CSV."""
    db = SessionLocal()
    try:
        import csv

        detections = db.query(Detection).filter(Detection.mission_id == mission_id).all()
        if not detections:
            return None

        filename = f"detections_{mission_id}_{datetime.now().strftime('%Y%m%d')}.csv"
        filepath = os.path.join(settings.MEDIA_PATH, "reports", filename)
        os.makedirs(os.path.dirname(filepath), exist_ok=True)

        with open(filepath, "w", newline="") as f:
            writer = csv.writer(f)
            writer.writerow(["ID", "Object Class", "Count", "Confidence", "Detected At"])
            for det in detections:
                writer.writerow([
                    det.id,
                    det.object_class,
                    det.count,
                    det.confidence,
                    det.detected_at,
                ])

        return filepath
    except Exception as e:
        print(f"CSV export error: {e}")
        return None
    finally:
        db.close()
